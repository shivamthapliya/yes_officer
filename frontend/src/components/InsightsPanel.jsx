import { Sparkles } from 'lucide-react'

import { INSIGHT_LABELS, letterFor } from '../lib/format'

const CATEGORY_TAB = {
  COMMON_DOUBT: 'canary',
  CONFUSION: 'pink',
  MISCONCEPTION: 'apricot',
  UNCOUNTED_RESPONSE: 'sky',
  STUDENT_QUESTION: 'lilac',
  ENGAGEMENT: 'mint',
}

const STATUS_NOTE = {
  LIVE: 'Updating live from chat',
  FINALIZING: 'Analysing the last messages…',
  COMPLETE: 'Final analysis',
  FAILED: 'Analysis stopped early',
  IDLE: '',
}

function optionLabel(optionId, questions) {
  for (const q of questions || []) {
    const opt = q.options?.find((o) => o.id === optionId)
    if (opt) return `Option ${letterFor(opt.position)} (${opt.label})`
  }
  return null
}

export function InsightItem({ insight, questions }) {
  const option = insight.referenced_option_id && optionLabel(insight.referenced_option_id, questions)
  return (
    <li className="insight">
      <div className="insight-top">
        <span className="cat-chip" style={{ '--tab': `var(--tab-${CATEGORY_TAB[insight.category]})` }}>
          {INSIGHT_LABELS[insight.category]}
        </span>
        <span className="ai-label" title="Generated by AI from chat. Not a verified fact.">
          AI inference{insight.confidence != null && ` · ${Math.round(insight.confidence * 100)}%`}
        </span>
        <span className="meta">
          {insight.support_count} {insight.support_count === 1 ? 'message' : 'messages'}
        </span>
      </div>
      <h3>{insight.topic_label}</h3>
      <p>
        {insight.summary}
        {insight.student_name && <> · about <strong>{insight.student_name}</strong></>}
        {option && <> · mentions {option}</>}
      </p>
    </li>
  )
}

/**
 * Teacher-only AI panel. `snapshot` is whatever useInsightsDisplay decided to
 * show; the panel never decides timing itself.
 */
export function InsightsPanel({ snapshot, hasPending, questions, scope, onScopeChange, className = '' }) {
  const insights = snapshot?.insights || []
  return (
    <section className={`panel ${className}`} aria-labelledby="insights-title">
      <div className="panel-head">
        <Sparkles size={18} aria-hidden="true" />
        <h2 id="insights-title">AI insights</h2>
        <span className="spacer" />
        {snapshot && <span className="meta">v{snapshot.version}</span>}
      </div>
      {onScopeChange && (
        <div style={{ padding: '10px 16px 0' }}>
          <div className="segmented" role="group" aria-label="Insight scope">
            <button type="button" aria-pressed={scope === 'question'} onClick={() => onScopeChange('question')}>
              This question
            </button>
            <button type="button" aria-pressed={scope === 'poll'} onClick={() => onScopeChange('poll')}>
              Whole poll
            </button>
          </div>
        </div>
      )}
      <div className="panel-body" aria-live="polite">
        {snapshot?.analysis_status && STATUS_NOTE[snapshot.analysis_status] && (
          <p className="pending-note">
            {snapshot.analysis_status === 'FINALIZING' && <span className="spinner" aria-hidden="true" style={{ width: 12, height: 12 }} />}
            {STATUS_NOTE[snapshot.analysis_status]}
            {hasPending && ' · newer update queued'}
          </p>
        )}
        {insights.length === 0 ? (
          <p className="muted" style={{ fontSize: 'var(--t-sm)', padding: '12px 0' }}>
            Nothing yet. As students chat during the poll, recurring doubts, confusion and answers typed in chat
            show up here.
          </p>
        ) : (
          <ul style={{ listStyle: 'none', margin: 0, padding: 0 }}>
            {insights.map((i) => (
              <InsightItem key={i.id} insight={i} questions={questions} />
            ))}
          </ul>
        )}
      </div>
    </section>
  )
}
